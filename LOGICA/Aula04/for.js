// Era uma vez os laças de repetição da logica de programação e o laço FOR era o mais utilizado por economizar espaço e trazer praticidade para o desenvolvimento.
// Para utilizar o for é necessario ter um contador para delimitemos a quantidade de vezes que algo sera repetido. A estrutura do FOR recebe inicialização, condição e incremento

console.log("Vou ta contando até 10 ai ceis saem correndo");

// Inicialização   Condição    Incremento
for(let i = 0;     i<= 10;        i +=2 ) {
    console.log(i);
}

console.log("Correeeeee!!!!!!!!!");